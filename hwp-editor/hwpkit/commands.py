@dataclass
class 맥락:
    """명령을 실행할 때 넘겨주는 것들."""

    문서객체: 문서
    값: dict[str, Any] = field(default_factory=dict)
    알림: Callable[[str], None] | None = None

    def 얻기(self, 이름: str, 기본값: Any = None) -> Any:
        return self.값.get(이름, 기본값)

    def 정수(self, 이름: str, 기본값: int = 0) -> int:
        값 = self.값.get(이름, 기본값)
        try:
            return int(str(값).strip() or 기본값)
        except ValueError as 오류:
            raise 입력오류(f"'{이름}' 은 숫자여야 합니다: {값}") from 오류

    def 소수(self, 이름: str, 기본값: float = 0.0) -> float:
        값 = self.값.get(이름, 기본값)
        try:
            return float(str(값).strip() or 기본값)
        except ValueError as 오류:
            raise 입력오류(f"'{이름}' 은 숫자여야 합니다: {값}") from 오류

    def 참(self, 이름: str, 기본값: bool = False) -> bool:
        값 = self.값.get(이름, 기본값)
        if isinstance(값, str):
            return 값.strip().lower() in ("1", "true", "y", "예", "on")
        return bool(값)

    def 글(self, 이름: str, 기본값: str = "") -> str:
        값 = self.값.get(이름, 기본값)
        return "" if 값 is None else str(값)


@dataclass(frozen=True)
class 명령:
    """실행할 수 있는 기능 하나."""

    번호: str
    제목: str
    분류: str
    실행: Callable[[맥락], str | None]
    검색어: tuple[str, ...] = ()
    입력: tuple[입력항목, ...] = ()
    필요: tuple[str, ...] = ()  # '선택' | '표'
    설명: str = ""

    @property
    def 입력필요(self) -> bool:
        return bool(self.입력)


_등록: dict[str, 명령] = {}


def 명령등록(
    번호: str,
    제목: str,
    분류: str,
    검색어: Iterable[str] = (),
    입력: Iterable[입력항목] = (),
    필요: Iterable[str] = (),
    설명: str = "",
) -> Callable[[Callable[[맥락], str | None]], Callable[[맥락], str | None]]:
    """명령을 등록하는 데코레이터."""

    def 감싸기(함수: Callable[[맥락], str | None]) -> Callable[[맥락], str | None]:
        if 번호 in _등록:
            raise ValueError(f"이미 등록된 명령 번호입니다: {번호}")
        if 분류 not in 분류순서:
            raise ValueError(f"모르는 분류입니다: {분류}")
        도움말 = 설명
        if not 도움말 and 함수.__doc__:
            도움말 = 함수.__doc__.strip().splitlines()[0]
        _등록[번호] = 명령(
            번호=번호,
            제목=제목,
            분류=분류,
            실행=함수,
            검색어=tuple(검색어),
            입력=tuple(입력),
            필요=tuple(필요),
            설명=도움말,
        )
        return 함수

    return 감싸기


def 전체명령() -> list[명령]:
    return list(_등록.values())


def 찾기(번호: str) -> 명령:
    if 번호 not in _등록:
        raise 입력오류(f"없는 명령입니다: {번호}")
    return _등록[번호]


def 분류별명령() -> dict[str, list[명령]]:
    """분류 → 명령 목록. 화면 구성에 그대로 쓴다."""
    묶음: dict[str, list[명령]] = {이름: [] for 이름 in 분류순서}
    for 하나 in _등록.values():
        묶음[하나.분류].append(하나)
    return 묶음


def 검색(질의: str, 최대: int = 40) -> list[명령]:
    """제목·검색어·분류로 명령을 찾는다. (명령 팔레트)"""
    말 = (질의 or "").strip().lower()
    if not 말:
        return 전체명령()[:최대]
    조각들 = 말.split()
    점수목록: list[tuple[int, 명령]] = []
    for 하나 in _등록.values():
        본문 = " ".join((하나.제목, 하나.분류, 하나.설명, *하나.검색어)).lower()
        if not all(조각 in 본문 for 조각 in 조각들):
            continue
        점수 = 0
        if 하나.제목.lower().startswith(말):
            점수 += 10
        if 말 in 하나.제목.lower():
            점수 += 5
        점수 += sum(2 for 조각 in 조각들 if 조각 in 하나.제목.lower())
        점수목록.append((점수, 하나))
    점수목록.sort(key=lambda 쌍: (-쌍[0], 쌍[1].제목))
    return [하나 for _점수, 하나 in 점수목록[:최대]]


