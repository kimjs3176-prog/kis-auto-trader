"""보고서 마크업 파서 — 이 프로그램의 핵심 재편 지점.

원본에는 기관마다 `경남소제목`, `남해네모내용`, `서울서론박스`, `인천진행순서` …
처럼 같은 구성요소를 다시 구현한 함수가 871개 있었다. 실제로 그 함수들은 모두
"한 줄짜리 지시(제목/네모/원/표…)를 한/글 서식으로 그린다"는 같은 일을 한다.

그래서 파이프라인을 하나로 통합했다.

    텍스트 마크업  ─▶  요소 트리(이 파일)  ─▶  렌더러(features/report.py)

기관별 함수는 전부 없앴고, 겉모습 차이는 스타일 프리셋(presets/styles.json)과
사용자 양식으로 흡수한다.

마크업 문법 (한 줄에 하나, `종류: 내용`)::

    제목: 2026년 스마트농업 확산 계획
    소제목: 추진 배경
    네모: 현장 수요가 빠르게 늘고 있음
    원: 스마트팜 보급률 12% → 21%로 증가
    바: 시설원예 중심에서 노지까지 확대 필요
    표: 구분 | 2025년 | 2026년
    표: 예산 | 1,200 | 1,850
    참고: 세부 산출근거는 붙임 참조
    쪽나눔:
    본문: 별도 기호 없이 그대로 쓰는 문단

`- ` `* ` `## ` 같은 흔한 마크다운 기호도 알아듣는다.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

__all__ = ["요소", "표요소", "파싱", "종류설명", "예시마크업"]


