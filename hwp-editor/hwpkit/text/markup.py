# 마크다운/한글 문서에서 흔히 쓰는 기호 -> 마크업 종류
_기호규칙: tuple[tuple[re.Pattern[str], str], ...] = (
    (re.compile(r"^#\s+(?P<본문>.*)$"), "제목"),
    (re.compile(r"^##\s+(?P<본문>.*)$"), "소제목"),
    (re.compile(r"^###\s+(?P<본문>.*)$"), "중제목"),
    (re.compile(r"^[□■]\s*(?P<본문>.*)$"), "네모"),
    (re.compile(r"^[○◦●]\s*(?P<본문>.*)$"), "원"),
    (re.compile(r"^[-*·]\s+(?P<본문>.*)$"), "바"),
    (re.compile(r"^[※*]{1,2}\s*(?P<본문>.*)$"), "별"),
    (re.compile(r"^\|(?P<본문>.*)\|?$"), "표"),
)


@dataclass
class 요소:
    """마크업 한 줄이 만들어내는 문서 구성요소."""

    종류: str
    내용: str = ""
    번호: int | None = None  # 소제목/중제목 자동 번호
    원본줄: int = 0

    @property
    def 비어있음(self) -> bool:
        return not self.내용.strip()


@dataclass
class 표요소(요소):
    """연속된 `표:` 줄이 하나로 합쳐진 표."""

    행들: list[list[str]] = field(default_factory=list)
    머리글: bool = True

    @property
    def 열수(self) -> int:
        return max((len(행) for 행 in self.행들), default=0)

    @property
    def 행수(self) -> int:
        return len(self.행들)


def _종류정규화(이름: str) -> str | None:
    이름 = 이름.strip()
    if 이름 in 종류설명:
        return 이름
    return _별칭.get(이름)


def _줄해석(줄: str) -> tuple[str, str] | None:
    """한 줄에서 (종류, 내용) 을 뽑는다. 해석 불가면 None."""
    본문 = 줄.rstrip()
    if not 본문.strip():
        return ("빈줄", "")

    # `종류: 내용` 형태 (콜론은 전각도 허용)
    m = re.match(r"^\s*([가-힣A-Za-z]{1,6})\s*[:：]\s*(.*)$", 본문)
    if m:
        종류 = _종류정규화(m.group(1))
        if 종류:
            return (종류, m.group(2).strip())

    for 규칙, 종류 in _기호규칙:
        m = 규칙.match(본문.strip())
        if m:
            return (종류, m.group("본문").strip())

    return ("본문", 본문.strip())


def 파싱(마크업: str, 자동번호: bool = True) -> list[요소]:
    """마크업 텍스트를 요소 목록으로 바꾼다.

    - 연속된 `표:` 줄은 하나의 `표요소` 로 합친다.
    - 자동번호=True 면 소제목/중제목에 1, 2, 3 … 번호를 매긴다.
    """
    요소들: list[요소] = []
    표버퍼: list[list[str]] = []
    표시작줄 = 0

    def 표닫기() -> None:
        nonlocal 표버퍼
        if 표버퍼:
            요소들.append(표요소(종류="표", 행들=표버퍼, 원본줄=표시작줄))
            표버퍼 = []

    for 줄번호, 줄 in enumerate(re.split(r"\r\n|\r|\n", 마크업 or ""), start=1):
        해석 = _줄해석(줄)
        if 해석 is None:  # pragma: no cover - _줄해석 은 항상 값을 준다
            continue
        종류, 내용 = 해석

        if 종류 == "표":
            if not 표버퍼:
                표시작줄 = 줄번호
            칸 = [칸.strip() for 칸 in re.split(r"\||\t", 내용)]
            표버퍼.append([칸 for 칸 in 칸 if 칸 != ""] or [""])
            continue
        표닫기()

        if 종류 == "빈줄" and (not 요소들 or 요소들[-1].종류 == "빈줄"):
            continue  # 앞뒤 빈 줄은 버린다
        요소들.append(요소(종류=종류, 내용=내용, 원본줄=줄번호))

    표닫기()
    while 요소들 and 요소들[-1].종류 == "빈줄":
        요소들.pop()

    if 자동번호:
        소 = 중 = 0
        for 항 in 요소들:
            if 항.종류 == "소제목":
                소 += 1
                중 = 0
                항.번호 = 소
            elif 항.종류 == "중제목":
                중 += 1
                항.번호 = 중
    return 요소들


