"""화면 색·글꼴 — 토스(Toss) 앱 배색을 참고했다.

토스 화면에서 가져온 규칙은 넷이다.

1. 아주 옅은 회색 바탕(`바탕`) 위에 **흰 카드**를 얹는다.
2. 칸을 테두리로 나누지 않는다. **여백과 둥근 모서리**로 나눈다.
3. 주 색은 **파랑 하나**뿐이고, 나머지는 회색조로 눌러 둔다.
4. 글자는 **진한 먹빛 → 보통 회색 → 흐린 회색** 세 단계로만 쓴다.

분류마다 색을 달리하긴 하지만, 카드 전체를 물들이지 않고 아이콘 배지에만
옅게(`섞기`) 써서 화면이 알록달록해지지 않게 했다.
"""

from __future__ import annotations

__all__ = [
    "바탕",
    "카드",
    "카드가리킴",
    "테두리",
    "파랑",
    "파랑진하게",
    "파랑옅게",
    "진한글",
    "보통글",
    "흐린글",
    "글꼴",
    "섞기",
    "분류모습",
]

# ---------------------------------------------------------------- 색
바탕 = "#F2F4F6"  # 패널 바탕 (토스의 그 옅은 회색)
카드 = "#FFFFFF"
카드가리킴 = "#F1F5FD"  # 카드를 가리켰을 때
테두리 = "#E5E8EB"
파랑 = "#3182F6"
파랑진하게 = "#1B64DA"  # 눌렀을 때
파랑옅게 = "#E8F3FF"
진한글 = "#191F28"
보통글 = "#4E5968"
흐린글 = "#8B95A1"
꺼짐 = "#B0C8F0"  # 못 누르는 파란 단추

글꼴 = "맑은 고딕"

#: 분류 → (아이콘 글머리, 강조색).
#: 글머리는 KS X 1001 안의 기호만 골라 한글 글꼴에서 네모로 깨지지 않게 했다.
_분류모습 = {
    "블록 편집": ("¶", "#3182F6"),
    "표": ("▦", "#15C47E"),
    "서식": ("◎", "#7C5CFC"),
    "문서": ("§", "#FF8A00"),
    "보고서 만들기": ("▣", "#F04452"),
    "양식·메일머지": ("◇", "#2AC1BC"),
    "일괄 처리": ("▶", "#6155F5"),
    "도구": ("◈", "#6B7684"),
}
_모름모습 = ("■", "#6B7684")


def _쪼개기(색값: str) -> tuple[int, int, int]:
    말 = 색값.lstrip("#")
    if len(말) != 6:
        raise ValueError(f"#RRGGBB 형태여야 합니다: {색값}")
    return int(말[0:2], 16), int(말[2:4], 16), int(말[4:6], 16)


def 섞기(앞: str, 뒤: str, 비율: float) -> str:
    """두 색을 섞는다. `비율` 은 앞 색이 차지하는 몫(0~1).

    tkinter 캔버스에는 투명도가 없어서, 옅은 색이 필요하면 미리 흰색과 섞어 둔다.
    """
    몫 = min(1.0, max(0.0, 비율))
    앞값, 뒤값 = _쪼개기(앞), _쪼개기(뒤)
    섞인것 = tuple(round(하나 * 몫 + 저것 * (1 - 몫)) for 하나, 저것 in zip(앞값, 뒤값))
    return "#%02X%02X%02X" % 섞인것


def 분류모습(분류: str) -> tuple[str, str]:
    """분류 → (글머리, 강조색). 모르는 분류도 안전하게 받아 준다."""
    return _분류모습.get(분류, _모름모습)


def 배지색(강조: str) -> str:
    """아이콘 배지 바탕 — 강조색을 흰색에 옅게 푼 색."""
    return 섞기(강조, 카드, 0.13)
