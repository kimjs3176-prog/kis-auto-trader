#: 분류 → (아이콘 글머리, 강조색).
#: 글머리는 KS X 1001 안의 기호만 골라 한글 글꼴에서 네모로 깨지지 않게 했다.
#: 색은 주 파랑과 나란히 놓아도 튀지 않게 짙은 쪽으로 잡았다.
_분류모습 = {
    "블록 편집": ("¶", "#2447D6"),
    "표": ("▦", "#0E8F63"),
    "서식": ("◎", "#6B3FD1"),
    "문서": ("§", "#B86B00"),
    "보고서 만들기": ("▣", "#C8354A"),
    "양식·메일머지": ("◇", "#0E8F92"),
    "일괄 처리": ("▶", "#3B31B8"),
    "도구": ("◈", "#55617A"),
}
_모름모습 = ("■", "#55617A")


def _쪼개기(색값: str) -> tuple[int, int, int]:
    말 = 색값.lstrip("#")
    if len(말) != 6:
        raise ValueError(f"#RRGGBB 형태여야 합니다: {색값}")
    return int(말[0:2], 16), int(말[2:4], 16), int(말[4:6], 16)


def 섞기(앞: str, 뒤: str, 비율: float) -> str:
    """두 색을 섞는다. `비율` 은 앞 색이 차지하는 몫(0~1).

    tkinter 캔버스에는 투명도가 없어서, 옅은 색이 필요하면 미리 흰색과 섞어 둔다.
    """
    몫 = min(1.0, max(0.0, 비율))
    앞값, 뒤값 = _쪼개기(앞), _쪼개기(뒤)
    섞인것 = tuple(round(하나 * 몫 + 저것 * (1 - 몫)) for 하나, 저것 in zip(앞값, 뒤값))
    return "#%02X%02X%02X" % 섞인것


#: 그림자에 쓰는 밑색 — 파란빛이 도는 회색. 검정으로 깔면 탁해 보인다.
_그늘밑색 = "#8A9AC0"


def 그늘(뒷색: str, 세기: float) -> str:
    """`뒷색` 위에 얹을 그림자 색.

    tkinter 캔버스에는 투명도가 없어서, 카드 뒤에 옅은 색 둥근네모를 몇 겹
    깔아 그림자를 흉내 낸다. 세기를 0.06 → 0.03 처럼 줄여 가며 겹치면
    번지는 그림자가 된다.
    """
    return 섞기(_그늘밑색, 뒷색, min(0.9, max(0.0, 세기)))


def 분류모습(분류: str) -> tuple[str, str]:
    """분류 → (글머리, 강조색). 모르는 분류도 안전하게 받아 준다."""
    return _분류모습.get(분류, _모름모습)


def 배지색(강조: str) -> str:
    """아이콘 배지 바탕 — 강조색을 흰색에 옅게 푼 색."""
    return 섞기(강조, 카드, 0.15)
