# ------------------------------------------------------------------ 순수 계산
def 머리글행인가(행들: list[list[str]]) -> bool:
    """첫 행이 머리글인지 판단한다.

    규칙(예측할 수 있게 단순히 정했다): 행이 둘 이상이고, 첫 행의 모든 칸이
    * 숫자가 아니거나
    * 연도로 보이는 네 자리 수(1900~2100)
    이면 머리글로 본다.

    이 판단이 없으면 '구분 | 2025 | 2026' 의 연도가 합계·증감 계산에 섞이고,
    반대로 첫 칸이 글자라는 이유만으로 '가 | 10' 같은 실제 자료 행을 빼먹는다.
    자동 판단이 어긋나는 표에서는 `머리글있음` 을 직접 지정하면 된다.
    """
    if len(행들) < 2 or not 행들[0]:
        return False
    글자칸있음 = False
    for 값 in 행들[0]:
        수 = 실수읽기(값)
        if 수 is None:
            글자칸있음 = True
            continue
        if not (수 == int(수) and 1900 <= int(수) <= 2100):
            return False  # 연도로 보기 어려운 숫자가 있으면 자료 행
    return 글자칸있음


def _계산대상(행들: list[list[str]], 머리글있음: bool | None) -> tuple[list[list[str]], bool]:
    머리글 = 머리글행인가(행들) if 머리글있음 is None else 머리글있음
    return (행들[1:] if 머리글 else 행들), 머리글


def 합계행값(
    행들: list[list[str]],
    라벨: str = "합계",
    방식: str = "합계",
    콤마: bool = True,
    머리글있음: bool | None = None,
) -> list[str]:
    """열별로 합계(또는 평균·최대·최소)를 계산해 새 행 값을 만든다.

    머리글있음=None 이면 첫 행이 머리글인지 스스로 판단해 계산에서 뺀다.
    숫자가 하나도 없는 열은 빈 칸으로 두고, 첫 칸에는 라벨을 넣는다.
    """
    if not 행들:
        raise 입력오류("계산할 표 내용이 없습니다.")
    대상, _머리글 = _계산대상(행들, 머리글있음)
    if not 대상:
        raise 입력오류("머리글만 있어 계산할 값이 없습니다.")

    열수 = max(len(행) for 행 in 행들)
    결과: list[str] = []
    for 열 in range(열수):
        숫자들 = [
            수
            for 행 in 대상
            if (수 := 실수읽기(행[열] if 열 < len(행) else "")) is not None
        ]
        if not 숫자들:
            결과.append(라벨 if 열 == 0 else "")
            continue
        결과.append(수표기(_모으기(숫자들, 방식), 콤마))
    if 결과 and not 실수읽기(결과[0]) is None:
        # 첫 열도 숫자였다면 라벨 자리가 없으므로 앞에 라벨을 덧붙이지 않고 그대로 둔다.
        pass
    elif 결과:
        결과[0] = 라벨
    return 결과


def _모으기(숫자들: list[Decimal], 방식: str) -> Decimal:
    if 방식 == "합계":
        return sum(숫자들, Decimal(0))
    if 방식 == "평균":
        return sum(숫자들, Decimal(0)) / len(숫자들)
    if 방식 == "최대":
        return max(숫자들)
    if 방식 == "최소":
        return min(숫자들)
    raise 입력오류(f"모르는 계산: {방식}", "합계, 평균, 최대, 최소 중에서 고르세요.")


def 증감열값(
    행들: list[list[str]],
    앞열: int,
    뒤열: int,
    방식: str = "증감",
    자리수: int = 1,
    기호포함: bool = True,
    머리글있음: bool | None = None,
) -> list[str]:
    """두 열을 비교해 증감 열 값을 만든다.

    방식: 증감(차이) | 증감률(%) | 둘다
    머리글 행과, 숫자를 읽을 수 없는 행은 빈 칸으로 둔다.
    ('2025 → 2026' 처럼 연도 머리글끼리 계산되지 않게 한다)
    """
    if 방식 not in ("증감", "증감률", "둘다"):
        raise 입력오류(f"모르는 방식: {방식}", "증감, 증감률, 둘다 중에서 고르세요.")
    머리글 = 머리글행인가(행들) if 머리글있음 is None else 머리글있음
    결과: list[str] = []
    for 번호, 행 in enumerate(행들):
        if 머리글 and 번호 == 0:
            결과.append("")
            continue
        앞 = 실수읽기(행[앞열]) if 앞열 < len(행) else None
        뒤 = 실수읽기(행[뒤열]) if 뒤열 < len(행) else None
        if 앞 is None or 뒤 is None:
            결과.append("")
            continue
        차이 = 뒤 - 앞
        기호 = ("↑" if 차이 > 0 else "↓" if 차이 < 0 else "-") if 기호포함 else ""
        차이글 = 수표기(abs(차이)) + 기호
        if 방식 == "증감":
            결과.append(차이글 if 차이 else ("-" if 기호포함 else "0"))
            continue
        율 = (abs(차이) / abs(앞) * 100) if 앞 else Decimal(0)
        율글 = f"{수표기(round(율, 자리수))}%{기호}"
        결과.append(율글 if 방식 == "증감률" else f"{차이글}({수표기(round(율, 자리수))}%)")
    return 결과


def 환산값(값: str, 배수: Decimal, 자리수: int = 0, 콤마: bool = True) -> str:
    """숫자 한 칸을 단위 환산한다. 숫자가 없으면 원래 값을 그대로 둔다."""
    수 = 실수읽기(값)
    if 수 is None:
        return 값
    return 수표기(round(수 * 배수, 자리수), 콤마)


# ------------------------------------------------------------------ 표 읽기
def 표값읽기(문서객체: 문서, 범위: 셀범위 | None = None) -> tuple[list[list[str]], 셀범위]:
    """선택한 셀 블록을 행×열 표로 읽는다.

    주소로 셀을 찾으므로 병합된 셀이 있어도 자리가 밀리지 않는다.
    (원본은 목록 번호를 등차수열로 계산해 병합 셀에서 어긋났다)
    """
    범위 = 범위 or 문서객체.셀블록범위()
    행들: list[list[str]] = []
    for 행 in range(범위.행수):
        줄: list[str] = []
        for 열 in range(범위.열수):
            if 문서객체.셀주소로이동(범위, 범위.시작.열 + 열, 범위.시작.행 + 행):
                줄.append(문서객체.셀텍스트().strip())
            else:
                줄.append("")
        행들.append(줄)
    문서객체.취소()
    return 행들, 범위


def 행정렬(
    행들: list[list[str]],
    기준열: int,
    오름차순: bool = True,
    머리글있음: bool | None = None,
) -> list[list[str]]:
    """표를 열 하나를 기준으로 줄 세운다. (순수 계산)

    * 기준열은 **사람이 세는 번호**(1부터)로 받는다.
    * 그 칸이 숫자면 숫자로, 아니면 글자로 견준다. 숫자와 글자가 섞여 있으면
      숫자를 앞에 둔다(금액 표에서 '-', '해당없음' 같은 칸이 맨 뒤로 가게).
    * 머리글 행은 자리에 그대로 둔다.
    * 같은 값끼리는 원래 차례를 지킨다(파이썬 정렬이 안정 정렬이다).
    """
    if not 행들:
        return []
    자리 = 기준열 - 1
    if 자리 < 0 or 자리 >= max(len(줄) for 줄 in 행들):
        raise 입력오류(f"표에 없는 열입니다: {기준열}")

    대상, 머리글 = _계산대상(행들, 머리글있음)

    def 열쇠(줄: list[str]) -> tuple[int, Decimal, str]:
        값 = 줄[자리] if 자리 < len(줄) else ""
        수 = 실수읽기(값)
        if 수 is None:
            # (1, 0, 글자) — 숫자 칸(0, …) 보다 뒤로 간다.
            return (1, Decimal(0), 값.strip())
        return (0, Decimal(str(수)), "")

    줄세움 = sorted(대상, key=열쇠, reverse=not 오름차순)
    return ([행들[0]] if 머리글 else []) + 줄세움


# ------------------------------------------------------------------ 표 편집
def 합계행넣기(
    문서객체: 문서,
    방식: str = "합계",
    라벨: str = "",
    콤마: bool = True,
    머리글있음: bool | None = None,
) -> str:
    """선택한 범위 아래에 합계(소계) 행을 추가하고 열별 계산값을 채운다."""
    행들, 범위 = 표값읽기(문서객체)
    if 범위.행수 < 1 or 범위.열수 < 1:
        raise 상태오류("합계를 낼 셀을 선택하세요.")
    값들 = 합계행값(
        행들, 라벨=라벨 or 방식, 방식=방식, 콤마=콤마, 머리글있음=머리글있음
    )

    with 문서객체.한번에(f"{방식} 행 넣기"), 문서객체.화면정지():
        # 선택 범위의 마지막 행 첫 칸으로 가서 아래에 줄을 하나 추가한다.
        if not 문서객체.셀주소로이동(범위, 범위.시작.열, 범위.끝.행):
            raise 상태오류("선택한 범위의 마지막 줄을 찾지 못했습니다.")
        문서객체.실행("Cancel")
        문서객체.실행("TableInsertLowerRow")
        문서객체.실행("TableLowerCell")
        for 자리, 값 in enumerate(값들):
            문서객체.셀텍스트쓰기(값)
            if 자리 != len(값들) - 1:
                문서객체.실행("TableRightCell")
        문서객체.취소()
    return f"{방식} 행을 넣었습니다: {' | '.join(값 for 값 in 값들 if 값)}"


def 증감열넣기(
    문서객체: 문서,
    방식: str = "증감",
    머리글글: str = "증감",
    자리수: int = 1,
    머리글있음: bool | None = None,
) -> str:
    """선택한 범위의 마지막 두 숫자 열을 비교해 오른쪽에 증감 열을 추가한다."""
    행들, 범위 = 표값읽기(문서객체)
    if 범위.열수 < 2:
        raise 상태오류(
            "비교할 열이 두 개 이상 필요합니다.", "머리글까지 포함해 두 열 이상을 선택하세요."
        )
    앞열, 뒤열 = 범위.열수 - 2, 범위.열수 - 1
    값들 = 증감열값(
        행들, 앞열, 뒤열, 방식=방식, 자리수=자리수, 머리글있음=머리글있음
    )
    if not any(값들):
        raise 상태오류("숫자를 읽을 수 있는 행이 없습니다.")

    with 문서객체.한번에(f"{방식} 열 넣기"), 문서객체.화면정지():
        if not 문서객체.셀주소로이동(범위, 범위.끝.열, 범위.시작.행):
            raise 상태오류("선택한 범위의 마지막 열을 찾지 못했습니다.")
        문서객체.실행("Cancel")
        문서객체.실행("TableInsertRightColumn")
        문서객체.실행("TableRightCell")
        for 자리, 값 in enumerate(값들):
            쓸값 = 머리글글 if (자리 == 0 and not 값 and 머리글글) else 값
            문서객체.셀텍스트쓰기(쓸값)
            if 자리 != len(값들) - 1:
                문서객체.실행("TableLowerCell")
        문서객체.취소()
    채움 = sum(1 for 값 in 값들 if 값)
    return f"{방식} 열을 넣었습니다. ({채움}행 계산)"


def 단위환산(
    문서객체: 문서,
    방향: str = "원→천원",
    자리수: int = 0,
    머리글도바꾸기: bool = True,
) -> str:
    """선택한 셀의 숫자를 단위 환산하고, 첫 행의 단위 표기도 함께 고친다."""
    if 방향 not in 단위배수:
        raise 입력오류(f"모르는 환산 방향: {방향}", f"가능: {', '.join(단위배수)}")
    배수 = 단위배수[방향]
    앞단위, 뒤단위 = _단위이름[방향]

    행들, 범위 = 표값읽기(문서객체)
    바뀐 = 0
    머리글바뀜 = 0

    with 문서객체.한번에(f"단위 환산 {방향}"), 문서객체.화면정지():
        for 행번호, 행 in enumerate(행들):
            for 열번호, 값 in enumerate(행):
                if not 값:
                    continue
                수 = 실수읽기(값)
                if 수 is None:
                    # 숫자가 없는 칸은 머리글로 보고 단위 표기만 고친다.
                    if 머리글도바꾸기 and 앞단위 in 값:
                        새값 = 값.replace(앞단위, 뒤단위)
                        if 문서객체.셀주소로이동(
                            범위, 범위.시작.열 + 열번호, 범위.시작.행 + 행번호
                        ):
                            문서객체.셀텍스트쓰기(새값)
                            머리글바뀜 += 1
                    continue
                새값 = 환산값(값, 배수, 자리수)
                if 새값 != 값 and 문서객체.셀주소로이동(
                    범위, 범위.시작.열 + 열번호, 범위.시작.행 + 행번호
                ):
                    문서객체.셀텍스트쓰기(새값)
                    바뀐 += 1
        문서객체.취소()

    말 = f"{바뀐}칸을 {방향} 으로 환산했습니다."
    if 머리글바뀜:
        말 += f" 단위 표기 {머리글바뀜}곳도 고쳤습니다."
    return 말


def 표정렬(
    문서객체: 문서,
    기준열: int = 1,
    오름차순: bool = True,
    머리글있음: bool | None = None,
) -> str:
    """선택한 셀 범위의 줄을 열 하나 기준으로 다시 세운다.

    셀 값만 바꿔 넣으므로 표 모양(테두리·배경·병합)은 그대로 남는다.
    """
    행들, 범위 = 표값읽기(문서객체)
    if 범위.행수 < 2:
        raise 상태오류("줄을 세우려면 두 줄 이상 골라야 합니다.")

    새행들 = 행정렬(행들, 기준열, 오름차순, 머리글있음)
    if 새행들 == 행들:
        return "이미 정렬돼 있습니다."

    with 문서객체.한번에("표 정렬"), 문서객체.화면정지():
        for 행자리, 줄 in enumerate(새행들):
            for 열자리, 값 in enumerate(줄):
                if 문서객체.셀주소로이동(
                    범위, 범위.시작.열 + 열자리, 범위.시작.행 + 행자리
                ):
                    문서객체.셀텍스트쓰기(값)
        문서객체.취소()
    차례말 = "오름차순" if 오름차순 else "내림차순"
    return f"{기준열}번째 열 기준 {차례말}으로 {len(새행들)}줄을 다시 세웠습니다."
