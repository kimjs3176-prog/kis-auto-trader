"""자동 목차 만들기.

원본 `제목목차` 는 '2025년 사업계획', '행정안전부' 처럼 내용이 코드에 박혀 있어
실제 문서에는 쓸 수 없었다. 여기서는 **문서에 이미 있는 제목을 읽어** 목차를 만든다.

제목 판별은 글머리 기호(□ ○ -)와 번호 매기기(`1.`, `가.`, `1)`)를 본다.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from ..core.document import 문서
from ..core.errors import 상태오류

__all__ = ["제목", "제목추출", "목차문구", "목차생성"]

# 회사 양식은 "□ 아래 ㅇ" 을 한글 낱자 `ㅇ` 로 쓰라고 정해 두었다.
# 원 기호(○)만 보면 정작 양식대로 쓴 문서에서 목차가 비어 나온다.
_기호수준 = {"□": 1, "■": 1, "ㅁ": 1, "○": 2, "◦": 2, "●": 2, "ㅇ": 2, "-": 3, "▶": 1, "◇": 2}
_번호꼴 = (
    (re.compile(r"^\s*(\d+)\.\s+(?P<본문>\S.*)$"), 1),
    (re.compile(r"^\s*([가-하])\.\s+(?P<본문>\S.*)$"), 2),
    (re.compile(r"^\s*(\d+)\)\s+(?P<본문>\S.*)$"), 3),
)


@dataclass(frozen=True)
class 제목:
    """문서에서 찾은 제목 한 줄."""

    수준: int
    내용: str
    줄번호: int

    @property
    def 들여쓰기(self) -> str:
        return "  " * (self.수준 - 1)


def 제목추출(텍스트: str, 최대수준: int = 2, 최소길이: int = 2) -> list[제목]:
    """본문에서 제목으로 볼 수 있는 줄을 뽑는다.

    최대수준=1 이면 □ 수준만, 2 면 ○ 수준까지 목차에 넣는다.
    """
    결과: list[제목] = []
    for 줄번호, 줄 in enumerate(re.split(r"\r\n|\r|\n", 텍스트 or ""), start=1):
        본문 = 줄.strip()
        if len(본문) < 최소길이:
            continue

        수준 = None
        제목내용 = None
        머리 = 본문[0]
        if 머리 in _기호수준 and len(본문) > 1 and 본문[1] in " \t":
            수준 = _기호수준[머리]
            제목내용 = 본문[1:].strip()
        else:
            for 꼴, 기본수준 in _번호꼴:
                m = 꼴.match(본문)
                if m:
                    수준 = 기본수준
                    제목내용 = m.group("본문").strip()
                    break

        if 수준 is None or not 제목내용 or 수준 > 최대수준:
            continue
        # 문장으로 보이는 줄(마침표로 끝나고 긴 줄)은 제목이 아니라고 본다.
        if len(제목내용) > 60 and 제목내용.endswith((".", "다", "요")):
            continue
        결과.append(제목(수준=수준, 내용=제목내용, 줄번호=줄번호))
    return 결과


def 목차문구(제목들: list[제목], 쪽번호: dict[int, int] | None = None) -> list[str]:
    """목차에 넣을 줄 목록을 만든다. (쪽번호를 알면 뒤에 붙인다)"""
    줄들 = []
    for 하나 in 제목들:
        말 = f"{하나.들여쓰기}{하나.내용}"
        쪽 = (쪽번호 or {}).get(하나.줄번호)
        줄들.append(f"{말}\t{쪽}" if 쪽 else 말)
    return 줄들


def 목차생성(
    문서객체: 문서,
    최대수준: int = 2,
    제목글: str = "목  차",
    표스타일: str = "선없음",
    문서앞에: bool = True,
) -> str:
    """문서의 제목을 읽어 목차를 만들어 넣는다.

    목차는 2열 표(제목 | 쪽)로 넣어 줄이 밀려도 정렬이 유지된다.
    쪽번호는 한/글이 알려 주는 현재 쪽을 쓰되, 판단할 수 없으면 비워 둔다.
    """
    from . import table_ops
    from .format import 문단모양, 스타일적용

    본문 = 문서객체.전체텍스트()
    제목들 = 제목추출(본문, 최대수준=최대수준)
    if not 제목들:
        raise 상태오류(
            "목차로 넣을 제목을 찾지 못했습니다.",
            "제목 줄이 '□ ', '○ ', '1. ' 처럼 시작하는지 확인하세요.",
        )

    쪽번호 = _쪽번호찾기(문서객체, 제목들)
    쪽있음 = bool(쪽번호)

    with 문서객체.한번에("목차 만들기"), 문서객체.화면정지():
        if 문서앞에:
            문서객체.이동하기("문서처음")

        스타일적용(문서객체, "제목")
        문단모양(문서객체, 정렬="가운데")
        문서객체.문장입력(제목글)
        문서객체.문단(2)

        열수 = 2 if 쪽있음 else 1
        table_ops.표만들기(문서객체, 열수=열수, 행수=len(제목들), 행높이=7)
        문서객체.이동하기("표처음셀")
        for 하나 in 제목들:
            문서객체.셀텍스트쓰기(f"{하나.들여쓰기}{하나.내용}")
            문서객체.실행("TableRightCell")
            if 쪽있음:
                쪽 = 쪽번호.get(하나.줄번호)
                문서객체.셀텍스트쓰기(str(쪽) if 쪽 else "")
                문서객체.실행("TableRightCell")
        table_ops.표스타일적용(문서객체, 표스타일, 머리글있음=False)
        문서객체.실행("Cancel")
        문서객체.실행("CloseEx")
        문서객체.실행("MoveLineEnd")
        문서객체.쪽나눔()

    쪽말 = "쪽번호를 함께 넣었습니다." if 쪽있음 else "쪽번호는 확인할 수 없어 비워 두었습니다."
    return f"제목 {len(제목들)}개로 목차를 만들었습니다. {쪽말}"


def _쪽번호찾기(문서객체: 문서, 제목들: list[제목]) -> dict[int, int]:
    """제목마다 몇 쪽에 있는지 찾아본다.

    한/글이 쪽 정보를 주지 않는 환경(또는 찾기 실패)에서는 빈 표를 돌려주고,
    호출한 쪽은 쪽번호 없이 목차를 만든다. 억지로 추측하지 않는다.
    """
    from .find_replace import 찾기

    결과: dict[int, int] = {}
    if 문서객체.현재쪽() is None:
        return 결과

    with 문서객체.위치보존():
        for 하나 in 제목들:
            찾을말 = 하나.내용[:30]
            if not 찾을말:
                continue
            try:
                문서객체.이동하기("문서처음")
                찾기(문서객체, 찾을말)
                쪽 = 문서객체.현재쪽()
            except Exception:  # noqa: BLE001 - 못 찾으면 그 제목만 건너뛴다
                쪽 = None
            if 쪽:
                결과[하나.줄번호] = 쪽
    문서객체.취소()
    return 결과
