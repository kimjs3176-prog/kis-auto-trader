"""블록(선택 영역) 기능 — 텍스트 변환을 한/글에 연결한다.

원본은 버튼 하나에 메서드 하나씩(`블록콤마넣기`, `블록나이`, `맨앞어절제거`,
`블록오름차순` …) 붙어 있었다. 실제 로직은 모두 `text/` 의 순수 함수로 옮겼고,
이 파일은 "블록을 읽어 → 변환하고 → 되쓴다"는 한 가지 흐름만 담당한다.
"""

from __future__ import annotations

from typing import Callable

from ..core.document import 문서
from ..core.errors import 상태오류, 입력오류
from ..text import calc, transform
from ..text.numbers import 비율분배

__all__ = [
    "블록변환",
    "줄별변환실행",
    "정렬실행",
    "앞뒤붙임실행",
    "글머리붙이기",
    "계산실행",
    "비율분배실행",
    "블록통계",
]


def 블록변환(문서객체: 문서, 변환: Callable[[str], str], 이름: str = "블록 변환") -> str:
    """선택 영역 텍스트에 변환 함수를 적용한다. 결과 텍스트를 돌려준다."""
    원문 = 문서객체.선택텍스트()
    바뀐 = 변환(원문)
    if 바뀐 is None:
        raise 상태오류(f"{이름}: 바꿀 수 없는 내용입니다.")
    if 바뀐 == 원문:
        return 원문
    with 문서객체.한번에(이름):
        문서객체.선택교체(바뀐)
    return 바뀐


def 줄별변환실행(문서객체: 문서, 변환이름: str) -> str:
    """`text.transform.한줄변환` 표의 변환을 줄마다 적용한다.

    (콤마넣기·금액문구·날짜서식·만나이·개월수 등 20여 개 버튼을 하나로 통합)
    """
    if 변환이름 not in transform.한줄변환:
        raise 입력오류(
            f"모르는 변환: {변환이름}",
            f"쓸 수 있는 변환: {', '.join(transform.한줄변환)}",
        )
    return 블록변환(
        문서객체,
        lambda 원문: transform.줄별변환(원문, 변환이름),
        f"블록 {변환이름}",
    )


def 정렬실행(문서객체: 문서, 방식: str = "오름차순") -> str:
    return 블록변환(문서객체, lambda 원문: transform.정렬(원문, 방식), f"블록 {방식} 정렬")


def 앞뒤붙임실행(문서객체: 문서, 앞: str = "", 뒤: str = "", 지울글자수: int = 0) -> str:
    """줄마다 앞/뒤 문자열을 붙이고, 필요하면 앞 글자를 먼저 지운다."""
    def 변환(원문: str) -> str:
        값 = transform.맨앞제거(원문, 지울글자수) if 지울글자수 else 원문
        return transform.앞뒤붙임(값, 앞, 뒤)

    return 블록변환(문서객체, 변환, "블록 앞뒤 붙임")


def 글머리붙이기(문서객체: 문서, 글머리이름: str) -> str:
    """글머리 프리셋의 서식을 적용하고 기호를 줄마다 붙인다."""
    from .format import 글머리적용, 글머리목록

    정의 = 글머리목록().get(글머리이름)
    if 정의 is None:
        raise 입력오류(f"없는 글머리: {글머리이름}")
    원문 = 문서객체.선택텍스트()
    기호 = 글머리적용(문서객체, 글머리이름)  # 서식 먼저(블록 선택이 유지된다)
    바뀐 = transform.글머리교체(원문, 기호, 정의.get("들여쓰기", ""))
    if 바뀐 != 원문:
        with 문서객체.한번에(f"글머리 {글머리이름}"):
            문서객체.선택교체(바뀐)
    return 바뀐


def 계산실행(문서객체: 문서, 자리수: int = 0, 결과만: bool = False) -> str:
    """블록의 수식을 계산해 결과로 바꾼다."""
    def 변환(원문: str) -> str:
        문구 = calc.블록수식문구(원문, 자리수)
        return 문구.split(" = ", 1)[1] if 결과만 else 문구

    return 블록변환(문서객체, 변환, "블록 계산")


def 비율분배실행(문서객체: 문서, 항목: list[tuple[str, float]]) -> str:
    """블록의 금액을 지정 비율로 나눠 `1,000,000(국비 700,000, 지방비 300,000)` 형태로 만든다."""
    def 변환(원문: str) -> str:
        결과 = 비율분배(원문, 항목)
        if 결과 is None:
            raise 상태오류("금액을 읽을 수 없습니다.", "숫자가 포함된 부분을 선택하세요.")
        return 결과

    return 블록변환(문서객체, 변환, "금액 비율 분배")


def 블록통계(문서객체: 문서) -> dict[str, int]:
    """선택 영역의 글자·낱말·줄 수를 센다. (원본에 없던 기능)"""
    원문 = 문서객체.선택텍스트()
    줄들 = transform.줄나누기(원문)
    글자수 = len(원문.replace("\r", "").replace("\n", ""))
    공백제외 = len("".join(원문.split()))
    return {
        "줄수": len([줄 for 줄 in 줄들 if 줄.strip()]),
        "글자수": 글자수,
        "글자수_공백제외": 공백제외,
        "낱말수": len(원문.split()),
    }
