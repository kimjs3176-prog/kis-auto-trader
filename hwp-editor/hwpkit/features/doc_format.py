"""문서 서식 기준 — 받은 문서를 회사 보고서 양식에 맞춘다.

지금까지 '문서 서식 한 번에 정리' 는 서식을 **지우는** 일만 했다. 서식을 지우면
한/글 기본값(함초롬바탕 10pt)이 되는데, 회사 보고서 양식은 신명조 15pt·줄간격
160%·여백 12.7/20mm 라서 정리를 하고 나면 오히려 양식과 더 멀어졌다.

그래서 회사 양식 파일(「보고서 작성 기본 편집요건」)의 편집용지·문단모양·글자모양을
읽어 `presets/doc_standards.json` 에 기준으로 적어 두고, 정리할 때 그 기준을
**입히도록** 했다.

기준이 정하는 것:

* 편집용지 — A4, 위·아래 12.7mm, 좌·우 20mm, 머리말·꼬리말 12.7mm
* 본문 — 한양신명조 15pt, 줄간격 160%, 양쪽 정렬, 장평 100 / 자간 0
* 글머리 수준별 — `□` 15pt 진하게(문단위 10pt), `ㅇ` 15pt(8pt),
  `-` 15pt(5pt), `*` 중고딕 13pt(2pt)
* 글머리 기호 — 양식 지침 "`□` 아래 `ㅇ`" 에 따라 `○ ◦ ●` 를 한글 `ㅇ` 로 통일

수준을 알아내는 부분(`수준찾기`)과 기준을 읽는 부분은 한/글 없이도 시험할 수 있는
순수 계산으로 두었다.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, replace
from functools import lru_cache
from pathlib import Path

from ..core import units
from ..core.document import 문서
from ..core.errors import 상태오류, 입력오류
from .page import 여백

__all__ = [
    "수준서식",
    "문서서식기준",
    "기준이름들",
    "기준찾기",
    "수준찾기",
    "글머리통일규칙",
    "글머리통일",
    "용지기준적용",
    "문단기준적용",
    "기준적용",
    "적용요약",
]

_프리셋 = Path(__file__).resolve().parent.parent / "presets" / "doc_standards.json"

#: 글머리 기호 → 수준. 양식이 쓰는 `□ / ㅇ / - / *` 를 기준으로 하고,
#: 실무에서 섞여 들어오는 변형(`■`, `○`, `●`, `–`, `▪`)도 같은 수준으로 본다.
_수준기호: dict[str, int] = {
    "□": 1,
    "■": 1,
    "ㅁ": 1,
    "ㅇ": 2,
    "○": 2,
    "◦": 2,
    "●": 2,
    "-": 3,
    "–": 3,
    "—": 3,
    "*": 4,
    "▪": 4,
    "·": 4,
}

#: `1.` `2.` 처럼 번호로 시작하는 소제목. (양식의 "1. 헤드라인M 15Pt")
_번호꼴 = re.compile(r"^[ \t ]*\d{1,2}\.[ \t]+\S")
#: `2023. 9. 7.(목)` 같은 날짜. 보고서 첫 줄에 흔히 오지만 소제목이 아니다.
_날짜꼴 = re.compile(r"^[ \t ]*\d{2,4}\.[ \t]*\d{1,2}\.")

#: 문단을 훑을 때의 안전장치. 이보다 긴 문서는 여기까지만 손댄다.
_문단한계 = 3000


@dataclass(frozen=True)
class 수준서식:
    """한 수준(또는 본문·제목)에 입힐 서식."""

    이름: str
    폰트: str
    크기: float
    기호: str = ""
    수준: int | None = None
    진하게: bool | None = None
    정렬: str = "양쪽"
    줄간격: int = 160
    문단위pt: float = 0.0

    @property
    def 위여백(self) -> float:
        """문단 위 여백(mm). 기준은 '문단위 10pt' 처럼 포인트로 적혀 있다."""
        return units.pt_mm(self.문단위pt)

    @property
    def 한줄(self) -> str:
        굵기 = " 진하게" if self.진하게 else ""
        머리 = f"{self.기호} " if self.기호 else ""
        여유 = f", 문단위 {self.문단위pt:g}pt" if self.문단위pt else ""
        return f"{머리}{self.이름}: {self.폰트} {self.크기:g}pt{굵기}{여유}"


@dataclass(frozen=True)
class 문서서식기준:
    """양식 하나에서 뽑은 서식 기준."""

    이름: str
    설명: str
    용지: str
    여백값: 여백
    본문: 수준서식
    제목: 수준서식
    수준들: tuple[수준서식, ...]
    글머리표: tuple[tuple[str, str], ...] = ()
    장평: int = 100
    자간: int = 0

    def 수준서식찾기(self, 수준: int | None) -> 수준서식 | None:
        """수준 번호에 해당하는 서식. 기준에 없는 수준이면 None."""
        if 수준 is None:
            return None
        for 하나 in self.수준들:
            if 하나.수준 == 수준:
                return 하나
        return None

    @property
    def 요약(self) -> str:
        칸 = self.여백값
        return (
            f"{self.용지} · 여백 위{칸.위:g}/아래{칸.아래:g}/좌{칸.왼쪽:g}/우{칸.오른쪽:g}mm"
            f" · {self.본문.폰트} {self.본문.크기:g}pt · 줄간격 {self.본문.줄간격}%"
        )


@lru_cache(maxsize=1)
def _프리셋읽기() -> dict:
    return json.loads(_프리셋.read_text(encoding="utf-8"))


def 기준이름들() -> tuple[str, ...]:
    """쓸 수 있는 기준 이름. UI 선택지에 그대로 쓴다."""
    return tuple(_프리셋읽기().get("기준", {}))


def _수준서식만들기(정의: dict, 이름: str, 기본정렬: str = "양쪽") -> 수준서식:
    return 수준서식(
        이름=이름,
        폰트=str(정의["폰트"]),
        크기=float(정의["크기"]),
        기호=str(정의.get("기호", "")),
        수준=정의.get("수준"),
        진하게=정의.get("진하게"),
        정렬=str(정의.get("정렬", 기본정렬)),
        줄간격=int(정의.get("줄간격", 160)),
        문단위pt=float(정의.get("문단위pt", 0)),
    )


def 기준찾기(이름: str) -> 문서서식기준:
    """이름으로 기준을 읽어 온다."""
    정의 = _프리셋읽기().get("기준", {}).get(이름)
    if 정의 is None:
        raise 입력오류(
            f"없는 서식 기준: {이름}",
            f"쓸 수 있는 기준: {', '.join(기준이름들())}",
        )
    칸 = 정의.get("여백", {})
    본문정의 = 정의["본문"]
    본문 = _수준서식만들기(본문정의, "본문")
    # 본문은 문단 전체를 굵게/얇게 바꾸지 않는다. 양식이 "중요한 부분은 진하게"
    # 라고 정한 대로, 문장 안에서 강조한 곳을 정리가 지워 버리면 안 된다.
    본문 = replace(본문, 진하게=None)
    return 문서서식기준(
        이름=이름,
        설명=str(정의.get("설명", "")),
        용지=str(정의.get("용지", "A4")),
        여백값=여백(
            왼쪽=float(칸.get("왼쪽", 20)),
            오른쪽=float(칸.get("오른쪽", 20)),
            위=float(칸.get("위", 15)),
            아래=float(칸.get("아래", 15)),
            머리=float(칸.get("머리", 10)),
            꼬리=float(칸.get("꼬리", 10)),
        ),
        본문=본문,
        제목=_수준서식만들기(정의.get("제목", 본문정의), "제목", 기본정렬="가운데"),
        수준들=tuple(
            _수준서식만들기(하나, f"{하나.get('수준')}수준") for 하나 in 정의.get("수준", ())
        ),
        글머리표=tuple((낡은, 새것) for 낡은, 새것 in 정의.get("글머리통일", {}).items()),
        장평=int(본문정의.get("장평", 100)),
        자간=int(본문정의.get("자간", 0)),
    )


# ------------------------------------------------------------------ 순수 계산


def 수준찾기(줄: str) -> int | None:
    """문단 첫 글자를 보고 개요 수준을 알아낸다. 글머리가 아니면 None.

    `□ 추진배경` → 1, `  ㅇ 내용` → 2, `1. 추진배경` → 0(소제목).
    기호 뒤에 공백이 없으면(`-------`, `*강조*`) 글머리로 보지 않는다.
    """
    글 = 줄 or ""
    if _번호꼴.match(글) and not _날짜꼴.match(글):
        return 0
    본문 = 글.lstrip(" \t ")
    if len(본문) < 2 or 본문[1] not in " \t ":
        return None
    if not 본문[2:].strip():  # 기호만 있고 내용이 없는 줄
        return None
    return _수준기호.get(본문[0])


def 글머리통일규칙(기준: 문서서식기준) -> list[tuple[str, str]]:
    """찾아바꾸기에 넣을 (찾기, 바꾸기) 쌍. 기호 뒤 공백까지 붙여 안전하게 바꾼다."""
    return [(f"{낡은} ", f"{새것} ") for 낡은, 새것 in 기준.글머리표 if 낡은 != 새것]


# ------------------------------------------------------------------ 한/글 적용


@dataclass
class 적용요약:
    """기준 적용 결과."""

    기준이름: str
    한일: list[str]
    손댄문단: int = 0

    @property
    def 문구(self) -> str:
        if not self.한일:
            return f"'{self.기준이름}' 기준으로 바꿀 것이 없었습니다."
        return f"'{self.기준이름}' 기준 적용: " + ", ".join(self.한일)


def 글머리통일(문서객체: 문서, 기준: 문서서식기준) -> int:
    """`○ ◦ ●` 처럼 섞여 쓰인 글머리를 양식 기호로 통일한다. 바꾼 규칙 수."""
    from ..text.transform import 찾아바꾸기규칙
    from .find_replace import 문서전체바꾸기

    규칙들 = [
        찾아바꾸기규칙(찾기=찾기, 바꾸기=바꾸기, 정규식=False)
        for 찾기, 바꾸기 in 글머리통일규칙(기준)
    ]
    if not 규칙들:
        return 0
    문서전체바꾸기(문서객체, 규칙들)
    return len(규칙들)


def 용지기준적용(문서객체: 문서, 기준: 문서서식기준) -> None:
    """편집용지(용지 크기·여백)를 문서 전체에 맞춘다."""
    from .page import 용지설정

    용지설정(문서객체, 기준.용지, 기준.여백값, 적용범위=2)  # 2 = 문서 전체


def _자리읽기(문서객체: 문서) -> tuple | None:
    try:
        자리 = 문서객체.한글.GetPos()
    except Exception:  # noqa: BLE001 - 옛 버전에는 GetPos 가 없을 수 있다
        return None
    return tuple(자리) if 자리 is not None else None


def 문단순회(문서객체: 문서, 최대문단: int = _문단한계):
    """문서 처음부터 문단을 하나씩, **문단 본문을 선택한 상태로** 넘겨준다.

    문단 번호로 계산해 뛰어다니면 표·글상자가 섞인 문서에서 번호가 어긋난다.
    그래서 커서를 실제로 옮기며(`MoveNextParaBegin`) 자리가 더 움직이지 않을 때
    끝난 것으로 본다.
    """
    문서객체.이동하기("문서처음")
    첫자리 = _자리읽기(문서객체)
    if 첫자리 is None:
        raise 상태오류(
            "이 한/글에서는 문단을 하나씩 훑을 수 없습니다.",
            "한/글을 최신 버전으로 올린 뒤 다시 해 보세요.",
        )
    자리 = 첫자리
    센수 = 0
    while 센수 < 최대문단:
        문서객체.실행("MoveSelParaEnd")
        yield 문서객체.선택텍스트(필수=False)
        문서객체.취소()
        문서객체.실행("MoveNextParaBegin")
        새자리 = _자리읽기(문서객체)
        if 새자리 is None or 새자리 == 자리:
            break
        자리 = 새자리
        센수 += 1


def 문단기준적용(
    문서객체: 문서,
    기준: 문서서식기준,
    제목포함: bool = False,
    최대문단: int = _문단한계,
) -> int:
    """문단마다 글머리 수준을 보고 기준 서식을 입힌다. 손댄 문단 수를 돌려준다.

    표 안의 문단은 건드리지 않는다. 표는 칸 너비에 맞춰 글자 크기를 따로 잡는
    일이 많아, 본문 기준을 그대로 밀어 넣으면 칸이 넘친다.
    """
    from .format import 글자모양, 문단모양

    손댐 = 0
    첫줄 = True
    with 문서객체.한번에("문서 서식 기준 적용"), 문서객체.화면정지():
        for 글 in 문단순회(문서객체, 최대문단):
            if not (글 or "").strip():
                continue
            if 문서객체.표안:
                continue
            if 첫줄 and 제목포함:
                서식 = 기준.제목
            else:
                서식 = 기준.수준서식찾기(수준찾기(글)) or 기준.본문
            첫줄 = False
            글자모양(
                문서객체,
                폰트=서식.폰트,
                크기=서식.크기,
                진하게=서식.진하게,
                장평=기준.장평,
                자간=기준.자간,
            )
            문단모양(
                문서객체,
                정렬=서식.정렬,
                줄간격=서식.줄간격,
                위여백=서식.위여백,
            )
            손댐 += 1
    return 손댐


def 기준적용(
    문서객체: 문서,
    기준: 문서서식기준 | str,
    용지: bool = True,
    문단: bool = True,
    글머리: bool = True,
    제목포함: bool = False,
    최대문단: int = _문단한계,
) -> 적용요약:
    """회사 양식 기준을 문서에 입힌다."""
    규격 = 기준찾기(기준) if isinstance(기준, str) else 기준
    한일: list[str] = []
    손댐 = 0

    # 글머리를 먼저 통일해야 수준 판정이 양식 기호로 맞는다.
    if 글머리 and 글머리통일(문서객체, 규격):
        한일.append("글머리 기호")
    if 용지:
        용지기준적용(문서객체, 규격)
        칸 = 규격.여백값
        한일.append(f"편집용지({규격.용지} {칸.위:g}/{칸.왼쪽:g}mm)")
    if 문단:
        손댐 = 문단기준적용(문서객체, 규격, 제목포함=제목포함, 최대문단=최대문단)
        한일.append(f"문단 {손댐}개")
    return 적용요약(기준이름=규격.이름, 한일=한일, 손댄문단=손댐)
