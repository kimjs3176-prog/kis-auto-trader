# ------------------------------------------------------------------ 항목기호
def test_항목기호_차례가_편람과_같다():
    assert [공문글.항목기호(수준, 1) for 수준 in range(1, 9)] == [
        "1.", "가.", "1)", "가)", "(1)", "(가)", "①", "㉮",
    ]


def test_같은수준_순번이_이어진다():
    assert [공문글.항목기호(2, 번호) for 번호 in (1, 2, 3)] == ["가.", "나.", "다."]
    assert 공문글.항목기호(1, 12) == "12."
    assert 공문글.항목기호(2, 14) == "하."
    assert 공문글.항목기호(2, 15) == "가가."  # 열넷을 넘으면 두 글자로 잇는다


def test_들여쓴_깊이로_수준을_매긴다():
    항목들 = 공문글.본문줄들("가장 위\n  아래\n  아래 둘\n    더 아래\n다시 위")
    # '더 아래' 는 그 자리에 형제가 없어 기호를 붙이지 않는다(편람).
    assert [(하나.수준, 하나.기호) for 하나 in 항목들] == [
        (1, "1."), (2, "가."), (2, "나."), (3, ""), (1, "2."),
    ]


def test_단계를_건너뛰어_적어도_한_단계씩만_내려간다():
    항목들 = 공문글.본문줄들("위\n        많이 들여씀")
